"""Unit tests for the relation data generated by the 'interface_docs' local Sphinx extension."""

from __future__ import annotations

import json
import pathlib
import subprocess
import textwrap
import typing

import interface_docs
import pytest

_ROOT = pathlib.Path(__file__).resolve().parent.parent.parent

PROVIDER_APP: dict[str, typing.Any] = {
    '$defs': {
        'Mode': {'enum': ['tls', 'starttls'], 'type': 'string', 'description': 'How to connect.'},
        'Endpoint': {
            'properties': {
                'url': {'type': 'string', 'format': 'uri', 'description': 'Where to connect.'},
            },
            'required': ['url'],
            'type': 'object',
        },
    },
    'properties': {
        'host': {'type': 'string', 'minLength': 1, 'description': 'The host | name.'},
        'port': {'type': 'integer', 'minimum': 1, 'maximum': 65535},
        'mode': {'$ref': '#/$defs/Mode', 'default': 'tls'},
        'user': {'anyOf': [{'type': 'string'}, {'type': 'null'}], 'default': None},
        'endpoints': {'type': 'array', 'items': {'$ref': '#/$defs/Endpoint'}},
        'labels': {
            'contentMediaType': 'application/json',
            'contentSchema': {'type': 'object', 'additionalProperties': {'type': 'string'}},
            'type': 'string',
        },
    },
    'required': ['host', 'port', 'endpoints'],
    'type': 'object',
}
REQUIRER_UNIT: dict[str, typing.Any] = {
    # The same nested model as the provider uses, which is only documented once.
    '$defs': {'Endpoint': PROVIDER_APP['$defs']['Endpoint']},
    'properties': {
        'address': {'type': 'string', 'format': 'ipvanyaddress'},
        'endpoint': {'$ref': '#/$defs/Endpoint'},
    },
    'required': ['address'],
    'type': 'object',
}
DATABAGS: dict[str, dict[str, typing.Any] | None] = {
    'provider-app': PROVIDER_APP,
    'provider-unit': None,
    'requirer-app': None,
    'requirer-unit': REQUIRER_UNIT,
}


def test_relation_data_tables():
    markdown = interface_docs.render_relation_data(DATABAGS)
    assert markdown == textwrap.dedent("""\
        Generated from the [Pydantic schema](schema.py).

        ### Provider application databag

        | Field | Type | Required | Description |
        |---|---|---|---|
        | `host` | string, at least 1 character | yes | The host \\| name. |
        | `port` | integer, 1 to 65535 | yes |  |
        | `mode` | one of `tls`, `starttls` | no (default `tls`) | How to connect. |
        | `user` | string or null | no |  |
        | `endpoints` | list of `Endpoint` objects | yes |  |
        | `labels` | JSON-encoded mapping of string to string | no |  |

        #### `Endpoint`

        | Field | Type | Required | Description |
        |---|---|---|---|
        | `url` | string (URI) | yes | Where to connect. |

        ### Requirer unit databag

        | Field | Type | Required | Description |
        |---|---|---|---|
        | `address` | string (IP address) | yes |  |
        | `endpoint` | `Endpoint` object | no |  |

        Empty databags: provider unit, requirer application.""")


def test_relation_data_without_schema_link():
    markdown = interface_docs.render_relation_data(DATABAGS, link_schema=False)
    assert 'schema.py' not in markdown


@pytest.mark.parametrize(
    ('prop', 'expected'),
    [
        ({}, 'any'),
        ({'const': 1}, '`1`'),
        ({'enum': ['a']}, '`a`'),
        ({'type': 'array'}, 'list'),
        ({'type': 'array', 'items': {'enum': ['a', 'b']}}, 'list, each one of `a`, `b`'),
        ({'type': 'object'}, 'object'),
        ({'type': 'number', 'exclusiveMinimum': 0}, 'number, more than 0'),
        (
            {'type': 'number', 'exclusiveMinimum': 0, 'maximum': 1},
            'number, more than 0 and at most 1',
        ),
        ({'type': 'integer', 'exclusiveMaximum': 10}, 'integer, less than 10'),
        ({'const': ''}, '`""`'),
        (
            {'type': 'string', 'maxLength': 5, 'pattern': '^a'},
            'string, at most 5 characters, matching `^a`',
        ),
        ({'anyOf': [{'type': 'string'}, {'type': 'integer'}]}, 'string or integer'),
        ({'anyOf': [{'type': 'null'}]}, 'null'),
        ({'allOf': [{'type': 'boolean'}]}, 'boolean'),
    ],
)
def test_type(prop: dict[str, typing.Any], expected: str):
    assert interface_docs._type(prop, {}) == expected


def test_direction_diagram():
    diagram = interface_docs.render_direction_diagram(DATABAGS)
    assert diagram == textwrap.dedent("""\
        ```mermaid
        flowchart LR
            provider[Provider]
            requirer[Requirer]
            provider -->|"app: host, port, mode,<br>user, endpoints, labels"| requirer
            requirer -->|"unit: address, endpoint"| provider
        ```""")


def test_direction_diagram_all_empty():
    assert interface_docs.render_direction_diagram(dict.fromkeys(DATABAGS)) == ''


README = """\
# `foo/v0`

## Direction

The provider writes.

```mermaid
## Not a heading
```

## Behavior

- Something.

## Relation Data

[\\[Pydantic Schema\\]](./schema.py)

### Provider
"""


def test_add_generated_sections():
    result = interface_docs.add_generated_sections(README, DATABAGS)
    lines = result.splitlines()
    # The diagram goes at the end of the Direction section, after the existing fence.
    diagram_start = lines.index('flowchart LR') - 1
    assert lines[diagram_start - 2] == '```'
    assert lines.index('## Behavior') > diagram_start
    # The tables go directly under the Relation Data heading, before the hand-written content.
    heading = lines.index('## Relation Data')
    assert lines[heading + 2] == '### Provider application databag'
    assert lines.index('### Provider') > heading
    # The README already links the schema, so the generated content doesn't.
    assert 'Generated from the' not in result


def test_add_generated_sections_direction_ends_at_title():
    readme = '# `foo/v0`\n\n## Direction\n\nThe provider writes.\n\n# Another title\n'
    lines = interface_docs.add_generated_sections(readme, DATABAGS).splitlines()
    assert lines.index('```mermaid') < lines.index('# Another title')


def test_add_generated_sections_without_headings():
    result = interface_docs.add_generated_sections('# `foo/v0`\n\nSome text.\n', DATABAGS)
    lines = result.splitlines()
    heading = lines.index('## Relation data')
    assert lines[heading + 2] == 'Generated from the [Pydantic schema](schema.py).'
    # With no Direction section, the diagram leads the generated relation data.
    assert lines.index('```mermaid') > heading
    assert lines.index('```mermaid') < lines.index('### Provider application databag')


def test_schema_script_handles_both_conventions(tmp_path: pathlib.Path):
    new_style = tmp_path / 'new.py'
    new_style.write_text(
        textwrap.dedent("""\
            from pydantic import BaseModel

            class ProviderAppData(BaseModel):
                host: str

            ProviderUnitData = None
            RequirerAppData = None
            RequirerUnitData = None
        """)
    )
    old_style = tmp_path / 'old.py'
    old_style.write_text(
        textwrap.dedent("""\
            from interface_tester.schema_base import DataBagSchema
            from pydantic import BaseModel

            class Unit(BaseModel):
                address: str

            class RequirerSchema(DataBagSchema):
                unit: Unit
        """)
    )
    misnamed = tmp_path / 'misnamed.py'
    misnamed.write_text(
        textwrap.dedent("""\
            from pydantic import BaseModel

            class ProviderAppAData(BaseModel):
                host: str

            ProviderUnitData = None
            RequirerAppData = None
            RequirerUnitData = None
        """)
    )
    broken = tmp_path / 'broken.py'
    broken.write_text('raise RuntimeError("nope")\n')
    output = subprocess.check_output(
        [
            'uv',
            'run',
            '--no-project',
            '--with-requirements',
            str(_ROOT / 'schema-requirements.txt'),
            str(_ROOT / '.docs' / 'scripts' / 'interface_schemas.py'),
            str(new_style),
            str(old_style),
            str(misnamed),
            str(broken),
        ],
        text=True,
    )
    result = json.loads(output)
    new_bags = result[str(new_style)]['databags']
    assert list(new_bags['provider-app']['properties']) == ['host']
    assert new_bags['requirer-unit'] is None
    old_bags = result[str(old_style)]['databags']
    assert old_bags['provider-app'] is None
    assert old_bags['requirer-app'] is None
    assert list(old_bags['requirer-unit']['properties']) == ['address']
    assert 'does not define ProviderAppData' in result[str(misnamed)]['error']
    assert 'RuntimeError: nope' in result[str(broken)]['error']
